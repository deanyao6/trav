import { open, send, shot, check, results } from './ui-lib.mjs';
const { browser, page } = await open();
const thread = page.getByTestId('thread');
await send(page, 'h_dean', '@trav i paid €84 for dinner, split with everyone but Henry');
await thread.getByTestId('card-expense_confirm').waitFor();
await page.getByTestId('clock-morning').click();
await page.waitForTimeout(500);
await send(page, 'h_dean', '@trav settle now');
await page.waitForTimeout(500);
const cards = () => thread.locator('[data-testid="card-settle_up"]');
console.log('settle cards after settle now:', await cards().count());
await page.getByTestId('sendas-h_chase').click();
let last = cards().last();
console.log('Chase sees actions:', await last.locator('button').allInnerTexts());
await last.getByTestId('action-sent').click();
await page.waitForTimeout(500);
console.log('settle cards after Chase Sent:', await cards().count());
last = cards().last();
await last.scrollIntoViewIfNeeded();
const afterSent = await last.innerText();
console.log('LAST CARD after Sent:\n' + afterSent);
await shot(page, 'settle-ui-01-after-sent');
check('rendered card shows Chase sent status after Sent', /sent|paid/i.test(afterSent.replace(/Sent\s*$/m, '')), afterSent.replace(/\n/g, ' / '));
await page.getByTestId('sendas-h_dean').click();
last = cards().last();
await last.getByTestId('action-got_it').click();
await page.waitForTimeout(500);
last = cards().last();
await last.scrollIntoViewIfNeeded();
const afterGot = await last.innerText();
console.log('LAST CARD after Got it:\n' + afterGot);
await shot(page, 'settle-ui-02-after-got-it');
check('rendered card shows 1 paid after Got it', /paid|1 of 4/i.test(afterGot), afterGot.replace(/\n/g, ' / '));
console.log('settle cards total:', await cards().count());
const st = await fetch('http://127.0.0.1:5193/api/state').then((r) => r.json());
const su = st.groups[0].thread.filter((m) => m.card?.type === 'settle_up').at(-1);
console.log('server fallback:', su.text.split('\n').slice(0, 3).join(' / '));
console.log('card keys:', Object.keys(su.card), JSON.stringify(su.card.transfers ?? su.card.legs ?? '').slice(0, 400));
await browser.close();
console.log(`${results.filter((r) => r.ok).length}/${results.length}`);
